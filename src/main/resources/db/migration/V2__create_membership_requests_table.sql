CREATE TABLE membership_requests(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    message TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    reviewed_by BIGINT,
    reviewed_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT  fk_membership_requests_user
                                FOREIGN KEY (user_id)
                                REFERENCES users(id)
                                ON DELETE RESTRICT,
    CONSTRAINT fk_membership_requests_reviewer
                                FOREIGN KEY (reviewed_by)
                                REFERENCES users(id)
                                ON DELETE RESTRICT,
    CONSTRAINT chk_membership_requests_status
                                CHECK ( status IN ('PENDING','APPROVED','REJECTED'))
);
CREATE UNIQUE INDEX uk_membership_requests_one_pending_per_user
    ON membership_requests(user_id)
    WHERE status = 'PENDING';
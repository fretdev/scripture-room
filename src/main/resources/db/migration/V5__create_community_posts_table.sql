CREATE TABLE community_posts(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id BIGINT NOT NULL,
    scripture_study_id BIGINT NOT NULL,
    post_type VARCHAR(20) NOT NULL,
    title VARCHAR(150) NOT NULL,
    content TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_community_posts_author
        FOREIGN KEY (author_id)
        REFERENCES users(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_community_posts_scripture_study
        FOREIGN KEY (scripture_study_id)
        REFERENCES scripture_studies(id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_community_posts_post_type
        CHECK (post_type IN ('REFLECTION','SCRIPTURE'))
);

CREATE INDEX idx_community_posts_scripture_study_id
       ON community_posts(scripture_study_id);

CREATE INDEX idx_community_posts_author_id
       ON community_posts(author_id);
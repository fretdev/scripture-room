CREATE TABLE scripture_studies(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    roster_assignment_id BIGINT NOT NULL,
    title VARCHAR(100) NOT NULL,
    book VARCHAR(50) NOT NULL,
    start_chapter INTEGER NOT NULL,
    start_verse INTEGER NOT NULL,
    end_chapter INTEGER NOT NULL,
    end_verse INTEGER NOT NULL,
    translation_code VARCHAR(20) NOT NULL,
    lesson TEXT NOT NULL,
    reflection TEXT NOT NULL,
    application TEXT NOT NULL,
    closing_prayer TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    published_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_scripture_studies_roster_assignment
        FOREIGN KEY (roster_assignment_id)
        REFERENCES roster_assignments(id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_scripture_studies_status
        CHECK (status IN ('DRAFT','PUBLISHED'))
);

CREATE UNIQUE INDEX uk_scripture_studies_one_published_per_assignment
       ON scripture_studies(roster_assignment_id)
       WHERE status = 'PUBLISHED';
CREATE TABLE comments(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id BIGINT NOT NULL,
    community_post_id BIGINT NOT NULL,
    parent_comment_id BIGINT,
    content TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_comments_author
        FOREIGN KEY (author_id)
        REFERENCES users(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_comments_community_post
        FOREIGN KEY (community_post_id)
        REFERENCES community_posts(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_comments_parent_comment
        FOREIGN KEY (parent_comment_id)
        REFERENCES comments(id)
        ON DELETE RESTRICT
);

CREATE INDEX idx_comments_author_id
       ON comments(author_id);

CREATE INDEX idx_comments_community_post_id
       ON comments(community_post_id);

CREATE INDEX idx_comments_parent_comment_id
       ON comments(parent_comment_id);